"""Build docs/RESULTS.md from the most recent run of each spec in runs/.

Every number in the output is read from manifest.json / verdict.json /
result.json files; nothing is computed here except formatting and the
observed-order values already stored in the verdicts.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "runs"


def latest_runs():
    by_spec = {}
    for m in sorted(RUNS.glob("2*/manifest.json")):
        man = json.loads(m.read_text())
        by_spec[man["spec_file"]] = (m.parent, man)
    return by_spec


def fmt(v, f="{:.4e}"):
    return "—" if v is None else f.format(v)


def main():
    runs = latest_runs()
    out = ["# Results (generated by `scripts/summarize_runs.py` from `runs/`)", ""]
    env = None
    for d, man in runs.values():
        if (d / "environment.json").is_file():
            env = json.loads((d / "environment.json").read_text())
            break
    if env:
        out += ["## Environment of these runs", "",
                f"* MFEM: `{env['mfem'].get('version')}` git `{env['mfem'].get('git')}`; "
                f"libmfem.a SHA-256 `{env['mfem'].get('library_sha256')}`",
                f"* Solver binary SHA-256: `{env['solver_binary_sha256']}`",
                f"* Compiler: {env['cxx']}; CMake: {env['cmake']}; Python {env['python']}; "
                f"numpy {env['python_packages']['numpy']}; scipy {env['python_packages']['scipy']}",
                f"* OS: {env['os']}; CPUs: {env['cpu_count']}; RAM: {env['mem_total_mb']} MB",
                f"* MFEM build flags: " + ", ".join(f"{k}={v}" for k, v in env['mfem']['config'].items() if k.startswith('MFEM_USE_')),
                ""]

    out += ["## Terminal states", "", "| Spec | Final state | Code | Attempts | Run directory |", "|---|---|---|---|---|"]
    for spec, (d, man) in sorted(runs.items()):
        out.append(f"| `{spec}` | {man['final_state']} | {man['final_code']} | {len(man['attempts'])} | `{d.relative_to(ROOT)}` |")
    out.append("")

    out += ["## Convergence studies (accepted runs)", ""]
    for spec, (d, man) in sorted(runs.items()):
        if man["final_state"] != "ACCEPTED":
            continue
        att = sorted(d.glob("attempts/attempt_*"))[-1]
        v = json.loads((att / "verdict.json").read_text())
        ex = json.loads((att / "execution.json").read_text())
        pairs = {p["n_fine"]: p for p in v["convergence"]["pairs"]}
        out += [f"### `{spec}`", "",
                f"mesh `{ex['mesh_type']}`, p={ex['polynomial_order']}, assembly `{ex['assembly']}`, "
                f"solver `{ex['solver']}`; expected orders L2={v['convergence']['expected_l2_order']}, "
                f"H1-semi={v['convergence']['expected_h1_semi_order']}", "",
                "| n | h | DOFs | CG its | L2 error (verifier) | L2 (MFEM self-report) | H1-semi error (verifier) | L2 order | H1 order | rel. diff vs reference solve |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for lv in v["levels"]:
            p = pairs.get(lv["n"], {})
            out.append(f"| {lv['n']} | 1/{lv['n']} | {lv['num_dofs']} | {lv['solver_iterations']} | "
                       f"{fmt(lv['l2_error'])} | {fmt(lv['self_reported_l2_error'])} | {fmt(lv['h1_semi_error'])} | "
                       f"{fmt(p.get('l2_order'), '{:.4f}')} | {fmt(p.get('h1_semi_order'), '{:.4f}')} | "
                       f"{fmt(lv['reference_rel_diff'], '{:.2e}')} |")
        out.append("")

    out += ["## Bounded retry history", ""]
    for spec, (d, man) in sorted(runs.items()):
        if len(man["attempts"]) < 2:
            continue
        out += [f"### `{spec}` → {man['final_state']} ({man['final_code']})", "",
                "| Attempt | Mesh levels | Finest L2 error | Verdict | Codes |", "|---|---|---|---|---|"]
        for a in man["attempts"]:
            out.append(f"| {a['attempt']} | {a['mesh_levels']} | {fmt(a['errors'][-1]['l2'])} | {a['verdict']} | {a['failure_codes']} |")
        val = json.loads((d / "frozen" / "validation.json").read_text())
        out += ["", f"Frozen accuracy target `max_l2_error_finest` = {val['max_l2_error_finest']}; "
                f"frozen ValidationSpec SHA-256 `{man['frozen_sha256']['validation']}` (unchanged across attempts).", ""]

    out += ["## Fault × gate detection matrix", "",
            "Each row is a negative study that executed MFEM; columns are verifier check names; ✗ = check failed (fault detected by that gate).", ""]
    rows = []
    gate_names = []
    for spec, (d, man) in sorted(runs.items()):
        if "negative" not in spec or not man["attempts"]:
            continue
        att = sorted(d.glob("attempts/attempt_*"))[-1]
        v = json.loads((att / "verdict.json").read_text())
        failed = set()
        for lv in v["levels"]:
            failed |= {c["name"] for c in lv["checks"] if not c["passed"]}
        failed |= {c["name"] for c in v["study_checks"] if not c["passed"]}
        exits = sorted({lr["exit_meaning"] for lr in man["attempts"][-1]["levels"]})
        rows.append((Path(spec).stem, exits, failed, v["verdict"]))
        gate_names += [g for g in failed if g not in gate_names]
    out += ["| Negative study | Solver exit(s) | Verdict | " + " | ".join(f"`{g}`" for g in gate_names) + " |",
            "|---|---|---|" + "---|" * len(gate_names)]
    for name, exits, failed, verdict in rows:
        out.append(f"| {name} | {', '.join(exits)} | {verdict} | " + " | ".join("✗" if g in failed else "" for g in gate_names) + " |")
    out.append("")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/RESULTS.md from {len(runs)} runs")


if __name__ == "__main__":
    main()
